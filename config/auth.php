<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Authentication Defaults
    |--------------------------------------------------------------------------
    |
    | Guard по умолчанию и брокер сброса паролей. Guard отвечает за то, как пользователь
    | опознаётся в запросе; приложение целиком работает на сессионном web-guard'е, включая
    | AJAX-эндпоинты из routes/api.php (см. EnsureFrontendRequestsAreStateful в
    | bootstrap/app.php) — отдельного API-guard'а с токенами здесь нет.
    |
    */

    'defaults' => [
        'guard' => env('AUTH_GUARD', 'web'),
        'passwords' => env('AUTH_PASSWORD_BROKER', 'users'),
    ],

    /*
    |--------------------------------------------------------------------------
    | Authentication Guards
    |--------------------------------------------------------------------------
    |
    | Guard'ы описывают способ аутентификации для каждого запроса. Здесь он один, стоковый
    | session: логин через форму, состояние — в сессии, долгая память — через recaller-cookie
    | (см. providers ниже, где переопределено хранение его токена).
    |
    */

    'guards' => [
        'web' => [
            'driver' => 'session',
            'provider' => 'users',
        ],
    ],

    /*
    |--------------------------------------------------------------------------
    | User Providers
    |--------------------------------------------------------------------------
    |
    | Провайдер описывает, откуда берутся пользователи. Драйвер здесь не стоковый eloquent,
    | а eloquent-devices — App\Auth\DeviceRememberUserProvider, зарегистрированный в
    | AppServiceProvider. От обычного он отличается ровно одним: токен «запомнить меня»
    | хранится не в users.remember_token (один на пользователя), а строкой на устройство в
    | таблице remember_tokens. Без этого выход на телефоне перевыпускал общий токен и
    | разлогинивал заодно все остальные устройства.
    |
    */

    'providers' => [
        'users' => [
            'driver' => 'eloquent-devices',
            'model' => env('AUTH_MODEL', App\Models\User::class),
        ],
    ],

    /*
    |--------------------------------------------------------------------------
    | Resetting Passwords
    |--------------------------------------------------------------------------
    |
    | Не используется: в MVP нет сброса пароля по email, восстановление идёт через секретный
    | вопрос (см. README, «Пользователи и аутентификация», и PasswordRecoveryController).
    | Секция оставлена потому, что на неё ссылается defaults.passwords выше, и таблицы
    | password_reset_tokens в миграциях нет — брокер просто никем не вызывается.
    |
    */

    'passwords' => [
        'users' => [
            'provider' => 'users',
            'table' => env('AUTH_PASSWORD_RESET_TOKEN_TABLE', 'password_reset_tokens'),
            'expire' => 60,
            'throttle' => 60,
        ],
    ],

    /*
    |--------------------------------------------------------------------------
    | Password Confirmation Timeout
    |--------------------------------------------------------------------------
    |
    | Сколько секунд действует подтверждение пароля, прежде чем его попросят снова. Middleware
    | password.confirm в приложении сейчас нигде не навешан, так что значение стоковое.
    |
    */

    'password_timeout' => env('AUTH_PASSWORD_TIMEOUT', 10800),

];
