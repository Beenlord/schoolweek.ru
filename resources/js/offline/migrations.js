/**
 * Миграции схемы IndexedDB (см. offline/db.js — там они запускаются).
 *
 * Правила те же, что у обычных миграций БД:
 *
 * — Одна миграция на версию схемы, версии идут подряд начиная с 1, список только дополняется
 *   в конец. Версия базы = версия последней миграции, вручную её нигде указывать не нужно.
 * — Уже выпущенную миграцию не правят. У части пользователей она отработала в старом виде, и
 *   переписывание сделает их схему не такой, как у того, кто ставит приложение с нуля. Нужна
 *   правка — добавляется следующая миграция.
 * — Имена store'ов, индексов и полей внутри up() пишутся литералами, а не через константы из
 *   db.js. Миграция описывает схему на момент своей версии; если завтра store переименуют,
 *   константа в db.js поменяется — и старая миграция задним числом начала бы означать не то,
 *   что означала при выпуске.
 * — Откатов (down) нет и не будет: пользователю некуда «откатываться», у него просто более
 *   старая версия приложения, которая свою версию базы вообще не откроет.
 *
 * Ограничение самого IndexedDB, про которое легко забыть: весь upgrade выполняется внутри одной
 * транзакции versionchange, и она автоматически завершается, как только очередь микрозадач
 * опустеет без незавершённых запросов к ней. Поэтому внутри up() можно ждать (await) только
 * операции над переданной транзакцией tx — любой посторонний await (fetch, таймер, запрос к
 * другой базе) отпустит транзакцию, и она закроется прямо посреди миграции.
 *
 * Миграция данных, а не только схемы, делается через курсор по tx:
 *
 *     async up(db, tx) {
 *         let cursor = await tx.objectStore('days').openCursor();
 *
 *         while (cursor) {
 *             await cursor.update({ ...cursor.value, dirty: cursor.value.dirty ?? 0 });
 *             cursor = await cursor.continue();
 *         }
 *     },
 *
 * Создавать/удалять store'ы и индексы можно только здесь (db.createObjectStore и т.п.) —
 * IndexedDB не разрешает менять схему вне версионного апгрейда.
 *
 * @type {Array<{version: number, description: string, up: (db: IDBPDatabase, tx: IDBPTransaction) => void|Promise<void>}>}
 */
export const migrations = [
    {
        version: 1,
        description: 'Дни пользователя, ключ — дата; индекс by-dirty под неотправленные правки',
        up(db) {
            const days = db.createObjectStore('days', { keyPath: 'date' });
            days.createIndex('by-dirty', 'dirty');
        },
    },
    {
        version: 2,
        description: 'Отметки «неделя выкачана с сервера целиком» — чтобы офлайн отличать пустой день от незагруженного',
        up(db) {
            db.createObjectStore('weeks', { keyPath: 'weekStart' });
        },
    },
    {
        version: 3,
        description: 'События дня — правила, которые сетка недели раскрывает в конкретные дни',
        up(db) {
            db.createObjectStore('events', { keyPath: 'id' });
        },
    },
    {
        version: 4,
        description: 'Починка версии 3: у части устройств она успела создать store под старым именем',
        up(db) {
            // Эта миграция существует из-за нарушения правила, записанного в шапке файла: версия 3
            // была переписана уже после того, как отработала на устройствах разработки — сначала
            // она создавала store «recurringEvents», потом её переделали на «events». Номер версии
            // при этом не изменился, поэтому апгрейд на таких устройствах больше не запускался, а
            // код просил несуществующий store и падал с «One of the specified object stores was
            // not found».
            //
            // Отсюда и проверки существования: до этой точки база могла прийти в двух разных
            // состояниях, и оба нужно привести к одному.
            if (db.objectStoreNames.contains('recurringEvents')) {
                db.deleteObjectStore('recurringEvents');
            }

            if (!db.objectStoreNames.contains('events')) {
                db.createObjectStore('events', { keyPath: 'id' });
            }
        },
    },
];

// Самая частая ошибка при добавлении миграции — скопировать предыдущую и забыть поменять version
// (или, наоборот, перескочить номер). Молча это привело бы к тому, что часть пользователей
// осталась бы без нужного store'а, а поймали бы мы это уже по ошибкам в рантайме.
migrations.forEach((migration, index) => {
    if (migration.version !== index + 1) {
        throw new Error(
            `Миграции IndexedDB должны идти подряд с версии 1: на позиции ${index} ожидалась `
            + `версия ${index + 1}, а указана ${migration.version}.`,
        );
    }
});

/** Текущая версия схемы — она же версия, с которой открывается база. */
export const LATEST_VERSION = migrations[migrations.length - 1].version;
